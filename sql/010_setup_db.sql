-- 010_setup_db.sql
-- Competition database skeleton. Runs as SYSADMIN (one statement per MCP call, fully qualified names).
-- Idempotent: safe to re-run. Executed on 2026-09-09 (see docs/decisions.md).

-- NOTE: CREATE ROLE needs USERADMIN/ACCOUNTADMIN; the role is created in 000_admin_manual.sql.
--       Until then everything is owned by SYSADMIN (the MCP session role).

CREATE WAREHOUSE IF NOT EXISTS PRC_WH
  WITH WAREHOUSE_SIZE = 'XSMALL'
       GENERATION = '1'
       AUTO_SUSPEND = 60
       AUTO_RESUME = TRUE
       INITIALLY_SUSPENDED = TRUE
       ENABLE_QUERY_ACCELERATION = FALSE
       STATEMENT_TIMEOUT_IN_SECONDS = 3600
       STATEMENT_QUEUED_TIMEOUT_IN_SECONDS = 600
  COMMENT = 'PRC Data Challenge 2026. Resize to SMALL only for heavy feature builds, then back.';

CREATE DATABASE IF NOT EXISTS PRC_DC2026 COMMENT = 'PRC Data Challenge 2026 - taxi-out prediction';

CREATE SCHEMA IF NOT EXISTS PRC_DC2026.RAW  COMMENT = 'Official parquet files as loaded (permanent)';
CREATE SCHEMA IF NOT EXISTS PRC_DC2026.REF  COMMENT = 'External reference data: weather, airports, time zones, holidays (permanent)';
CREATE TRANSIENT SCHEMA IF NOT EXISTS PRC_DC2026.STG  DATA_RETENTION_TIME_IN_DAYS = 1 COMMENT = 'Typed, UTC-normalised movements';
CREATE TRANSIENT SCHEMA IF NOT EXISTS PRC_DC2026.FEAT DATA_RETENTION_TIME_IN_DAYS = 1 COMMENT = 'Feature tables';
CREATE TRANSIENT SCHEMA IF NOT EXISTS PRC_DC2026.ML   DATA_RETENTION_TIME_IN_DAYS = 1 COMMENT = 'Training wide tables, folds, predictions, experiments, submissions';
CREATE TRANSIENT SCHEMA IF NOT EXISTS PRC_DC2026.SUB  DATA_RETENTION_TIME_IN_DAYS = 1 COMMENT = 'Submission views';
DROP SCHEMA IF EXISTS PRC_DC2026.PUBLIC;

CREATE FILE FORMAT IF NOT EXISTS PRC_DC2026.RAW.PARQUET_FF
  TYPE = PARQUET
  USE_LOGICAL_TYPE = TRUE
  USE_VECTORIZED_SCANNER = TRUE
  BINARY_AS_TEXT = FALSE
  COMMENT = 'Official parquet. Timestamps become TIMESTAMP_LTZ/NTZ per logical type; normalise to NTZ UTC in COPY.';

CREATE STAGE IF NOT EXISTS PRC_DC2026.RAW.OFFICIAL_STAGE
  FILE_FORMAT = PRC_DC2026.RAW.PARQUET_FF
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'training_*.parquet, ranking.parquet, submitting.parquet';

CREATE STAGE IF NOT EXISTS PRC_DC2026.RAW.SQL_STAGE
  ENCRYPTION = (TYPE = 'SNOWFLAKE_SSE')
  DIRECTORY = (ENABLE = TRUE)
  COMMENT = 'Repository SQL scripts for EXECUTE IMMEDIATE FROM';

CREATE TABLE IF NOT EXISTS PRC_DC2026.ML.EXPERIMENTS (
  EXP_ID        STRING,
  CREATED_AT    TIMESTAMP_NTZ DEFAULT SYSDATE(),
  GIT_SHA       STRING,
  CONFIG_HASH   STRING,
  CONFIG        VARIANT,
  FOLD_SCHEME   STRING,
  RMSE_OVERALL  FLOAT,
  RMSE_BY_FOLD  VARIANT,
  RMSE_BY_AIRPORT VARIANT,
  TAIL_SHARE_P95 FLOAT,
  TRAIN_SECONDS FLOAT,
  NOTES         STRING
);

CREATE TABLE IF NOT EXISTS PRC_DC2026.ML.SUBMISSIONS (
  SUBMISSION_VERSION INTEGER,
  EXP_ID        STRING,
  CREATED_AT    TIMESTAMP_NTZ DEFAULT SYSDATE(),
  FILE_NAME     STRING,
  N_ROWS        INTEGER,
  LOCAL_CV_RMSE FLOAT,
  LB_RMSE       FLOAT,
  NOTES         STRING
);
