-- 020_raw_load.sql  (run after the 14 official parquet files are in @PRC_DC2026.RAW.OFFICIAL_STAGE)
-- One statement per MCP call. Column names are kept EXACTLY as in the parquet (case-sensitive, e.g. "MVT_ID_mvt").
-- Timestamps: PARQUET_FF has USE_LOGICAL_TYPE=TRUE, so UTC-adjusted timestamps arrive as TIMESTAMP_LTZ;
-- we store TIMESTAMP_NTZ in UTC explicitly in 030_stg.sql (RAW keeps the inferred types untouched).

-- 0) Inspect the inferred schema first (compare with docs/data_profile.md; check timestamp types).
SELECT * FROM TABLE(INFER_SCHEMA(LOCATION => '@PRC_DC2026.RAW.OFFICIAL_STAGE', FILES => 'training_2025-01-01_2025-02-01.parquet', FILE_FORMAT => 'PRC_DC2026.RAW.PARQUET_FF'));

-- 1) Training: one table for all 12 monthly files, plus lineage columns.
CREATE TABLE IF NOT EXISTS PRC_DC2026.RAW.TRAINING_MOVEMENTS
  USING TEMPLATE (
    SELECT ARRAY_CAT(
      ARRAY_AGG(OBJECT_CONSTRUCT(*)),
      [ OBJECT_CONSTRUCT('COLUMN_NAME','_SRC_FILE','TYPE','TEXT','NULLABLE',TRUE),
        OBJECT_CONSTRUCT('COLUMN_NAME','_SRC_ROW','TYPE','NUMBER','NULLABLE',TRUE),
        OBJECT_CONSTRUCT('COLUMN_NAME','_LOADED_AT','TYPE','TIMESTAMP_NTZ','NULLABLE',TRUE) ]
    )
    FROM TABLE(INFER_SCHEMA(LOCATION => '@PRC_DC2026.RAW.OFFICIAL_STAGE', FILES => 'training_2025-01-01_2025-02-01.parquet', FILE_FORMAT => 'PRC_DC2026.RAW.PARQUET_FF'))
  );

COPY INTO PRC_DC2026.RAW.TRAINING_MOVEMENTS
  FROM @PRC_DC2026.RAW.OFFICIAL_STAGE
  PATTERN = 'training_.*[.]parquet'
  FILE_FORMAT = (FORMAT_NAME = 'PRC_DC2026.RAW.PARQUET_FF')
  MATCH_BY_COLUMN_NAME = CASE_SENSITIVE
  INCLUDE_METADATA = (_SRC_FILE = METADATA$FILENAME, _SRC_ROW = METADATA$FILE_ROW_NUMBER, _LOADED_AT = METADATA$START_SCAN_TIME)
  ON_ERROR = ABORT_STATEMENT
  FORCE = FALSE;

-- 2) Ranking (Jan + Jul 2026; DEP rows have BLOCK_TIME_UTC_mvt and TAXITIME_SEC_mvt blanked).
CREATE TABLE IF NOT EXISTS PRC_DC2026.RAW.RANKING
  USING TEMPLATE (
    SELECT ARRAY_CAT(ARRAY_AGG(OBJECT_CONSTRUCT(*)),
      [ OBJECT_CONSTRUCT('COLUMN_NAME','_SRC_FILE','TYPE','TEXT','NULLABLE',TRUE),
        OBJECT_CONSTRUCT('COLUMN_NAME','_SRC_ROW','TYPE','NUMBER','NULLABLE',TRUE),
        OBJECT_CONSTRUCT('COLUMN_NAME','_LOADED_AT','TYPE','TIMESTAMP_NTZ','NULLABLE',TRUE) ])
    FROM TABLE(INFER_SCHEMA(LOCATION => '@PRC_DC2026.RAW.OFFICIAL_STAGE', FILES => 'ranking.parquet', FILE_FORMAT => 'PRC_DC2026.RAW.PARQUET_FF'))
  );

COPY INTO PRC_DC2026.RAW.RANKING
  FROM @PRC_DC2026.RAW.OFFICIAL_STAGE
  FILES = ('ranking.parquet')
  FILE_FORMAT = (FORMAT_NAME = 'PRC_DC2026.RAW.PARQUET_FF')
  MATCH_BY_COLUMN_NAME = CASE_SENSITIVE
  INCLUDE_METADATA = (_SRC_FILE = METADATA$FILENAME, _SRC_ROW = METADATA$FILE_ROW_NUMBER, _LOADED_AT = METADATA$START_SCAN_TIME)
  ON_ERROR = ABORT_STATEMENT
  FORCE = FALSE;

-- 3) Submission template (MVT_ID_mvt, TAXITIME_SEC_mvt). Keep the row order via _SRC_ROW.
CREATE TABLE IF NOT EXISTS PRC_DC2026.RAW.SUBMITTING
  USING TEMPLATE (
    SELECT ARRAY_CAT(ARRAY_AGG(OBJECT_CONSTRUCT(*)),
      [ OBJECT_CONSTRUCT('COLUMN_NAME','_SRC_ROW','TYPE','NUMBER','NULLABLE',TRUE) ])
    FROM TABLE(INFER_SCHEMA(LOCATION => '@PRC_DC2026.RAW.OFFICIAL_STAGE', FILES => 'submitting.parquet', FILE_FORMAT => 'PRC_DC2026.RAW.PARQUET_FF'))
  );

COPY INTO PRC_DC2026.RAW.SUBMITTING
  FROM @PRC_DC2026.RAW.OFFICIAL_STAGE
  FILES = ('submitting.parquet')
  FILE_FORMAT = (FORMAT_NAME = 'PRC_DC2026.RAW.PARQUET_FF')
  MATCH_BY_COLUMN_NAME = CASE_SENSITIVE
  INCLUDE_METADATA = (_SRC_ROW = METADATA$FILE_ROW_NUMBER)
  ON_ERROR = ABORT_STATEMENT
  FORCE = FALSE;

-- 4) Load audit (row counts per file must match the pyarrow counts recorded in docs/data_profile.md).
SELECT _SRC_FILE, COUNT(*) AS n_rows FROM PRC_DC2026.RAW.TRAINING_MOVEMENTS GROUP BY 1 ORDER BY 1;
SELECT COUNT(*) AS n_rows, COUNT(DISTINCT "MVT_ID_mvt") AS n_ids FROM PRC_DC2026.RAW.TRAINING_MOVEMENTS;
SELECT "PHASE_mvt", COUNT(*) FROM PRC_DC2026.RAW.RANKING GROUP BY 1;
SELECT COUNT(*) FROM PRC_DC2026.RAW.SUBMITTING;
